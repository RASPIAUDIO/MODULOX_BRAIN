"""Extract ASCII antialiased glyphs from the Noto VLW arrays already used by groovuino."""
from pathlib import Path
import re
import struct
import math

ROOT = Path(__file__).resolve().parents[1]
sources = ROOT.parent / "libraries/groovuino"
lines = ["// Generated by tools/display_fonts.py from the existing Arduino Noto font arrays.",
    "// Native-size alpha glyphs; no runtime file access, scaling or font allocation.",
    "#pragma once", "#include <cstdint>", "namespace display::fonts {",
    "struct Glyph { uint32_t offset; uint8_t width, height, advance; int8_t x, top; };",
    "struct Font { const Glyph* glyphs; const uint8_t* alpha; int ascent, height; };"]
total = 0
for name in ["NotoSansBold11", "NotoSansBold15", "NotoSansMonoSCB20", "NotoSansBold36"]:
    source_name = "NotoSansBold15" if name.endswith("11") else name
    source = (sources / (source_name + ".h")).read_text(encoding="utf-8")
    body = re.search(r"\b" + source_name + r"\[\].*?=\s*\{(.*?)\};", source, re.S).group(1)
    data = bytes(int(n, 16) for n in re.findall(r"0[xX]([0-9a-fA-F]{2})\b", body))
    count, _, _, _, ascent, descent = struct.unpack_from(">6i", data)
    cursor = 24 + count * 28
    glyphs, bitmap = {}, bytearray()
    for index in range(count):
        code, height, width, advance, top, x, _ = struct.unpack_from(">7i", data, 24 + index * 28)
        assert 0 <= width < 256 and 0 <= height < 256
        pixels = data[cursor:cursor + width * height]
        assert len(pixels) == width * height
        if 32 <= code <= 126:
            if name.endswith("11"):
                # Offline-only bilinear reduction for long captions in 70 px buttons.
                small_w, small_h = round(width * .75), round(height * .75)
                reduced = bytearray()
                for row in range(small_h):
                    sy = max(0, (row + .5) * height / small_h - .5)
                    y0 = min(math.floor(sy), height - 1); y1 = min(y0 + 1, height - 1)
                    fy = sy - y0
                    for col in range(small_w):
                        sx = max(0, (col + .5) * width / small_w - .5)
                        x0 = min(math.floor(sx), width - 1); x1 = min(x0 + 1, width - 1)
                        fx = sx - x0
                        a = pixels[y0 * width + x0] * (1 - fx) + pixels[y0 * width + x1] * fx
                        b = pixels[y1 * width + x0] * (1 - fx) + pixels[y1 * width + x1] * fx
                        reduced.append(round(a * (1 - fy) + b * fy))
                glyphs[code] = (len(bitmap), small_w, small_h, round(advance * .75), round(x * .75), round(top * .75))
                bitmap.extend(reduced)
            else:
                glyphs[code] = (len(bitmap), width, height, advance, x, top)
                bitmap.extend(pixels)
        cursor += width * height
    glyphs.setdefault(32, (0, 0, 0, (ascent + descent) // 4, 0, 0))
    assert all(code in glyphs for code in range(32, 127))
    ascent = max(g[5] for g in glyphs.values())
    bottom = max(g[2] - g[5] for g in glyphs.values())
    lines.append(f"inline constexpr uint8_t {name}_alpha[] = {{")
    for offset in range(0, len(bitmap), 32): lines.append(",".join(map(str, bitmap[offset:offset + 32])) + ",")
    lines.append("};")
    lines.append(f"inline constexpr Glyph {name}_glyphs[] = {{")
    lines.extend("{" + ",".join(map(str, glyphs[code])) + "}," for code in range(32, 127))
    lines.extend(["};", f"inline constexpr Font {name}{{{name}_glyphs, {name}_alpha, {ascent}, {ascent + bottom}}};"])
    total += len(bitmap)
lines.append("}")
(ROOT / "main/display_fonts.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Generated native Noto fonts and small-caption fallback: {total} alpha bytes plus glyph metrics in flash")
